package tours;

/**
 Статус экскурсии в жизненном цикле публикации.
 DRAFT - экскурсия создаётся, залы и точки ещё наполняются.
 READY - наполнение завершено, тур готов к проверке валидаторами.
 PUBLISHED - проверка пройдена, сгенерирована публичная ссылка.
 */
public enum TourStatus {
    DRAFT,
    READY,
    PUBLISHED
}
