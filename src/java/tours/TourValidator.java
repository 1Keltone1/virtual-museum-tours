package tours;

import java.util.List;

/**
 * Контракт валидатора тура.
 *
 * Одна операция — проверить тур и вернуть список сообщений об ошибках.
 * Пустой список означает, что тур корректен.
 *
 * Три реализации соответствуют трём автоматизируемым операциям
 * из таблицы КТ2:
 *   - PanoramaFormatValidator     (операция №1 «Проверить формат панорам»)
 *   - HotspotLinksValidator       (алгоритм №1, операция «Проверить связи точек перехода»)
 *   - GraphConnectivityValidator  (алгоритм №2, операция «Проверить связность графа тура»)
 *
 * Вызывающий код (Main) хранит все реализации в List<TourValidator>
 * и вызывает каждую через тип интерфейса — это и есть полиморфизм:
 * код работает с типом интерфейса, а не с конкретными классами.
 *
 * Такой подход позволяет добавлять новые проверки, не меняя вызывающий
 * код: достаточно написать ещё одну реализацию и положить её в список.
 */
public interface TourValidator {

    /**
     * Проверяет тур на корректность.
     *
     * @param tour экскурсия для проверки
     * @return список сообщений об ошибках; пустой список, если ошибок нет
     */
    List<String> validate(Tour tour);
}
